def get_animation(sheet_path, anim_dict, animation_name, scale=1):
    """
    Returns a list of pygame.Surface objects for a given animation.
    sheet_path: path to the spritesheet image
    anim_dict: dictionary containing lists of (x, y, w, h) tuples for each frame
    animation_name: key to look up in anim_dict
    scale: optional scale factor
    """
    sheet = pygame.image.load(sheet_path).convert()
    bg_color = sheet.get_at((0, 0))
    
    frames = []
    if animation_name in anim_dict:
        for rect in anim_dict[animation_name]:
            image = pygame.Surface((rect[2], rect[3])).convert()
            image.blit(sheet, (0, 0), (rect[0], rect[1], rect[2], rect[3]))
            image.set_colorkey(bg_color)
            
            if scale != 1:
                image = pygame.transform.scale(image, (int(rect[2] * scale), int(rect[3] * scale)))
                
            frames.append(image)
    return frames
